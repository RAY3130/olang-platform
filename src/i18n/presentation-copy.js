function localeKey(locale) {
  const value = String(locale || 'en').toLowerCase();
  if (value.startsWith('de')) return 'de';
  if (value.startsWith('ja')) return 'ja';
  return 'en';
}

function presentationCopy(locale) {
  const key = localeKey(locale);
  return { ...COPY[key], useByCategory: USE[key] };
}

function useText(categoryKey, locale) {
  return USE[localeKey(locale)][categoryKey] || '';
}

function seriesSlug(value) {
  return String(value || '')
    .toLowerCase()
    .replace(/\s+series$/i, '')
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

module.exports = { presentationCopy, useText, seriesSlug };
